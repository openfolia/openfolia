/** The default brand's mark for the title page: the artwork for light backgrounds (print is light). */
export const PRINT_LOGO =
  '@openfolia/theme/brand/openfolia-mark-color-light.svg';

let cached: { tokens: string; fontDir: string; logo: Uint8Array } | undefined;

/**
 * The theme as print needs it, read once: `tokens.typ`, the directory of
 * the TTF fonts and the default logo. Throws if the theme package is missing, so a broken install
 * fails the first PDF loudly instead of falling back to other fonts.
 */
export function printTheme(): {
  tokens: string;
  fontDir: string;
  logo: Uint8Array;
} {
  if (!cached) {
    const css = readFileSync(
      resolvePackageFile('@openfolia/theme/theme.css'),
      'utf8',
    );
    const fontDir = dirname(
      resolvePackageFile('@openfolia/theme/fonts/ttf/LICENSE.txt'),
    );
    for (const font of PRINT_FONTS) {
      if (!existsSync(join(fontDir, font))) {
        throw new Error(`@openfolia/theme: the print font ${font} is missing`);
      }
    }
    const logo = new Uint8Array(readFileSync(resolvePackageFile(PRINT_LOGO)));
    cached = { tokens: typstTokens(css), fontDir, logo };
  }
  return cached;
}
