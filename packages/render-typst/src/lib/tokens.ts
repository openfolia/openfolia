import { existsSync, readFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { str } from './render.js';

/**
 * The theme for print: `@openfolia/theme`'s design tokens as a Typst module, and
 * the directory of its fonts as TTF (Typst cannot read WOFF2). Both are read
 * from the theme package at run time, so the PDF changes with the theme and
 * nothing is copied.
 */

/** The file a package's export names, without importing it. */
const resolvePackageFile = (specifier: string) =>
  createRequire(import.meta.url).resolve(specifier);

/**
 * One theme value as Typst code, or undefined for a value print has no use
 * for. `oklch(L C h [/ a])` becomes Typst's `oklch(…)`, `rem` becomes `em`
 * (the CSS root size is the body text size in print), a font list keeps its
 * named families (the generic ones mean nothing to Typst).
 */
export function typstValue(css: string): string | undefined {
  const value = css.trim();
  const colour =
    /^oklch\(\s*([\d.]+)(%?)\s+([\d.]+)\s+([\d.]+)(?:deg)?\s*(?:\/\s*([\d.]+)(%?))?\s*\)$/.exec(
      value,
    );
  if (colour) {
    const [, l = '0', lPercent, c = '0', h = '0', alpha, alphaPercent] = colour;
    const lightness = lPercent ? Number(l) : Number(l) * 100;
    const args = [
      `${round(lightness)}%`,
      round(Number(c)),
      `${round(Number(h))}deg`,
    ];
    if (alpha !== undefined) {
      args.push(
        `${round(alphaPercent ? Number(alpha) : Number(alpha) * 100)}%`,
      );
    }
    return `oklch(${args.join(', ')})`;
  }
  const length = /^([\d.]+)rem$/.exec(value);
  if (length) return `${round(Number(length[1]))}em`;
  const families = [...value.matchAll(/'([^']+)'|"([^"]+)"/g)].map(
    (m) => (m[1] ?? m[2]) as string,
  );
  if (families.length > 0) {
    return `(${families.map((f) => `${str(f)},`).join(' ')})`;
  }
  return undefined;
}

const round = (n: number) => String(Math.round(n * 10000) / 10000);

/**
 * The custom properties of the theme's light values: every top-level rule
 * whose selector list holds `:root`, in order (a later one wins). Nested
 * blocks (`@media`) are not part of the light theme.
 */
export function lightTokens(css: string): [name: string, value: string][] {
  const plain = css.replace(/\/\*[\s\S]*?\*\//g, '');
  const tokens = new Map<string, string>();
  let found = false;
  for (const rule of plain.matchAll(/(?<=^|\})\s*([^{}@]+)\{([^{}]*)\}/g)) {
    const selectors = (rule[1] as string).split(',').map((s) => s.trim());
    if (!selectors.includes(':root')) continue;
    found = true;
    for (const decl of (rule[2] as string).split(';')) {
      const m = /^\s*--([a-z0-9-]+)\s*:\s*([\s\S]+?)\s*$/.exec(decl);
      if (m) tokens.set(m[1] as string, m[2] as string);
    }
  }
  if (!found) throw new Error('@openfolia/theme: theme.css has no :root block');
  return [...tokens];
}

/**
 * `tokens.typ`: the theme's light values as one Typst dictionary, `theme`,
 * keyed by the CSS names without `--` (`theme.muted-foreground`,
 * `theme.safety-danger`, `theme.radius`, `theme.font-sans`). Only the light
 * theme applies to print. Throws on a value it cannot carry over, so a new
 * kind of token fails the tests instead of going missing.
 */
export function typstTokens(css: string): string {
  const entries = lightTokens(css).map(([name, value]) => {
    const typst = typstValue(value);
    if (typst === undefined) {
      throw new Error(
        `@openfolia/theme: --${name} (${value}) has no Typst form`,
      );
    }
    return `  ${name}: ${typst},`;
  });
  return [
    '// Generated by @openfolia/render-typst from @openfolia/theme (theme.css, light values). Do not edit.',
    '#let theme = (',
    ...entries,
    ')',
    '',
  ].join('\n');
}

