/** A heading's anchor as the docs site makes it (github-slugger, lower case). */
export function anchor(text) {
  return String(text)
    .toLowerCase()
    .replace(/[^\p{L}\p{N}\s_-]/gu, '')
    .replace(/\s/g, '-');
}
