import type { INestApplication } from '@nestjs/common';
import {
  DocumentBuilder,
  SwaggerModule,
  type OpenAPIObject,
} from '@nestjs/swagger';
import type { z } from 'zod';
import {
  AUDIENCE_EXTENSION,
  AUTHORING_PARAMETERS,
  DELIVERY_AUDIENCE,
} from './delivery.decorator.js';
import { DELIVERY_DESCRIPTION } from './delivery-intro.js';
import { JSON_API_EXTENSION } from './json-api.decorators.js';
import { ErrorDocument, JSON_API } from './json-api.js';
import { NAMES_PEOPLE_EXTENSION, People } from './people.js';
import { PUBLIC_EXTENSION } from './public.decorator.js';
import { ScimErrorDocument } from '../../scim/api/scim.resources.js';
import { SCIM_EXTENSION, SCIM_MEDIA_TYPE } from '../../scim/api/scim-media.js';

type Responses = Record<
  string,
  { description?: string; content?: Record<string, unknown> }
>;

/** Every route with the token takes it. */
const USER_HEADER_PARAMETER = {
  name: 'X-Ccms-User',
  in: 'header',
  required: false,
  description:
    'Demo mode only (`CCMS_AUTH_MODE=demo`): the user ID to act as. The bearer token is still required; without demo mode the header is refused (400).',
  schema: { type: 'string' },
};

const errorResponse = (description: string, scim = false) => ({
  description,
  content: scim
    ? {
        [SCIM_MEDIA_TYPE]: {
          schema: { $ref: '#/components/schemas/ScimError' },
        },
      }
    : {
        [JSON_API]: { schema: { $ref: '#/components/schemas/ErrorDocument' } },
      },
});

/**
 * The OpenAPI document, generated from the controllers and their Zod
 * schemas, so it cannot drift from what the server does.
 */
export function createOpenApiDocument(app: INestApplication): OpenAPIObject {
  return build(app, false);
}

/**
 * The delivery document: only the operations marked `@DeliveryApi()`, with
 * the schemas they reference, its own title and introduction, and nothing
 * about demo mode (a consumer never acts as another user). Generated by the
 * same code from the same controllers and schemas.
 */
export function createDeliveryDocument(app: INestApplication): OpenAPIObject {
  return build(app, true);
}

function build(app: INestApplication, delivery: boolean): OpenAPIObject {
  const config = new DocumentBuilder()
    .setTitle(delivery ? 'OpenFolia delivery API' : 'OpenFolia content API')
    .setDescription(
      delivery
        ? DELIVERY_DESCRIPTION
        : [
            'Read access to a content repository: modules, manuals, resolved manuals, PDFs and images.',
            '',
            `JSON responses follow [JSON:API](https://jsonapi.org/format/) (\`${JSON_API}\`): resources are \`{ type, id, attributes, relationships, meta }\`; \`attributes\` hold stored data, \`meta\` what the server derives from it (validation issues, summaries). Lists take \`page[number]\` and \`page[size]\` and \`filter[…]\` where documented; other query parameters are rejected. Errors are \`{ errors: [{ status, title, detail, code, source?, meta? }] }\` on every route, binary ones included.`,
            '',
            'Every route except `/health` and this reference needs `Authorization: Bearer <token>`. A service account token (`ccms_sat_…`) acts as that service account, with its roles; the shared token (`CCMS_API_TOKEN`, only for local use and demo mode) acts as a read-only service, and in demo mode `X-Ccms-User` picks a seeded user to act as instead (`GET /me` shows who).',
            '',
            'Every content route reads at `?ref=` (a branch, tag or commit ID) and reports the commit it used in `X-Ccms-Commit`. Responses for a commit ID never change and are marked immutable; others revalidate with `ETag`.',
          ].join('\n'),
    )
    .setVersion('0.1')
    .addBearerAuth({
      type: 'http',
      scheme: 'bearer',
      description:
        "A service account's token (`ccms_sat_…`, issued by `POST /service-accounts/{id}/tokens`), or, for local use and demo mode, the server's shared `CCMS_API_TOKEN`.",
    })
    .addSecurityRequirements('bearer')
    .build();
  const document = SwaggerModule.createDocument(app, config, {
    operationIdFactory: (controller, method) =>
      `${controller.replace(/Controller$/, '')}_${method}`,
  });

  if (delivery) keepDeliveryOperations(document);
  documentPeople(document);

  for (const path of Object.values(document.paths)) {
    for (const operation of Object.values(path)) {
      if (
        typeof operation !== 'object' ||
        !operation ||
        !('responses' in operation)
      ) {
        continue;
      }
      const marked = operation as Record<string, unknown>;
      const responses = operation.responses as Responses;
      const isJsonApi = Boolean(marked[JSON_API_EXTENSION]);
      delete marked[JSON_API_EXTENSION];
      // SCIM's routes (#377) answer and take SCIM's media type, errors too.
      const isScim = Boolean(marked[SCIM_EXTENSION]);
      delete marked[SCIM_EXTENSION];
      const own = isScim ? SCIM_MEDIA_TYPE : JSON_API;
      // Errors are JSON:API everywhere (SCIM's on SCIM's routes); successes on JSON:API routes.
      for (const [status, response] of Object.entries(responses)) {
        const content = response.content;
        if (!content) continue;
        const isError = /^[45]/.test(status);
        if (isError) {
          // Whatever media type an error was declared under (the PDF route
          // declares `application/pdf`), the server sends JSON:API.
          const [first] = Object.values(content);
          if (first === undefined) continue;
          for (const type of Object.keys(content)) delete content[type];
          content[own] = first;
        } else if ((isJsonApi || isScim) && content['application/json']) {
          content[own] = content['application/json'];
          delete content['application/json'];
        }
      }
      // Request bodies on JSON:API routes are JSON:API too (SCIM's, SCIM's).
      const body = (
        operation as {
          requestBody?: { content?: Responses[string]['content'] };
        }
      ).requestBody?.content;
      if ((isJsonApi || isScim) && body?.['application/json']) {
        body[own] = body['application/json'];
        delete body['application/json'];
      }
      if (isJsonApi) {
        responses['400'] ??= errorResponse(
          'A query parameter the route does not support, or a malformed one.',
        );
        responses['406'] ??= errorResponse(
          `The \`Accept\` header rules out \`${JSON_API}\`.`,
        );
      }
      if (marked[PUBLIC_EXTENSION]) {
        delete marked[PUBLIC_EXTENSION];
        operation.security = [];
        continue;
      }
      responses['401'] ??= errorResponse('Missing or wrong API token.', isScim);
      if (delivery) continue;
      const unknownUser = 'Demo mode: `X-Ccms-User` names no user.';
      const forbidden = responses['403'];
      if (forbidden) {
        forbidden.description = `${forbidden.description ?? ''} Or: ${unknownUser}`;
      } else {
        responses['403'] = errorResponse(unknownUser, isScim);
      }
      const headerRefused = '`X-Ccms-User` sent while demo mode is off.';
      const badRequest = responses['400'];
      if (badRequest) {
        badRequest.description = `${badRequest.description ?? ''} Or: ${headerRefused}`;
      } else {
        responses['400'] = errorResponse(headerRefused, isScim);
      }
      operation.parameters = [
        ...((operation.parameters as unknown[] | undefined) ?? []),
        USER_HEADER_PARAMETER,
      ];
    }
  }
  document.components ??= {};
  document.components.schemas ??= {};
  document.components.schemas['ErrorDocument'] ??= toOpenApi(ErrorDocument);
  if (!delivery) {
    document.components.schemas['ScimError'] ??= toOpenApi(ScimErrorDocument);
  }
  if (delivery) pruneSchemas(document);
  return document;
}

/**
 * `meta.people` in the documents of the routes marked `@NamesPeople()` (the JSON:API interceptor
 * adds it to each), so no resource repeats it. Such a document is one for marked routes only.
 */
function documentPeople(document: OpenAPIObject): void {
  type Schema = {
    properties?: Record<string, Schema>;
    required?: string[];
    type?: string;
  };
  const schemas = (document.components?.schemas ?? {}) as Record<
    string,
    Schema
  >;
  const named = new Map<string, boolean>();
  for (const path of Object.values(document.paths)) {
    for (const operation of Object.values(path)) {
      if (!operation?.responses) continue;
      const marked = Boolean(operation[NAMES_PEOPLE_EXTENSION]);
      delete operation[NAMES_PEOPLE_EXTENSION];
      for (const [status, response] of Object.entries(
        operation.responses as Responses,
      )) {
        if (!status.startsWith('2')) continue;
        for (const media of Object.values(response.content ?? {})) {
          const ref = (media as { schema?: { $ref?: string } }).schema?.$ref;
          const name = ref && SCHEMA_REF.exec(ref)?.[1];
          if (!name) continue;
          if ((named.get(name) ?? marked) !== marked) {
            throw new Error(
              `${name} is the document of a route marked @NamesPeople() and of one that is not.`,
            );
          }
          named.set(name, marked);
        }
      }
    }
  }
  const people = toOpenApi(People) as Schema;
  for (const [name, marked] of named) {
    const schema = schemas[name];
    if (!marked || !schema?.properties) continue;
    const meta = (schema.properties['meta'] ??= { type: 'object' });
    meta.properties = { ...meta.properties, people };
    meta.required = [...(meta.required ?? []), 'people'];
    schema.required = [...new Set([...(schema.required ?? []), 'meta'])];
  }
}

/**
 * Drops every operation not marked for the delivery audience, then empty
 * paths, and the authoring parameters of those kept (`AUTHORING_PARAMETERS`).
 */
function keepDeliveryOperations(document: OpenAPIObject): void {
  for (const [route, item] of Object.entries(document.paths)) {
    for (const [method, operation] of Object.entries(item)) {
      const kept = operation as Record<string, unknown> | undefined;
      if (kept?.[AUDIENCE_EXTENSION] !== DELIVERY_AUDIENCE) {
        delete (item as Record<string, unknown>)[method];
      } else if (Array.isArray(kept['parameters'])) {
        kept['parameters'] = (kept['parameters'] as { name?: string }[]).filter(
          (p) => p.name === undefined || !AUTHORING_PARAMETERS.has(p.name),
        );
      }
    }
    if (Object.keys(item).length === 0) delete document.paths[route];
  }
}

const SCHEMA_REF = /^#\/components\/schemas\/(.+)$/;

/** Keeps the schemas the paths reference, directly or through each other. */
function pruneSchemas(document: OpenAPIObject): void {
  const schemas = (document.components?.schemas ?? {}) as Record<
    string,
    unknown
  >;
  const used = new Set<string>();
  const visit = (node: unknown): void => {
    if (Array.isArray(node)) return node.forEach(visit);
    if (typeof node !== 'object' || node === null) return;
    for (const [key, value] of Object.entries(node)) {
      const name =
        key === '$ref' && typeof value === 'string'
          ? SCHEMA_REF.exec(value)?.[1]
          : undefined;
      if (name === undefined) {
        visit(value);
      } else if (!used.has(name)) {
        used.add(name);
        visit(schemas[name]);
      }
    }
  };
  visit(document.paths);
  for (const name of Object.keys(schemas)) {
    if (!used.has(name)) delete schemas[name];
  }
}

const toOpenApi = (schema: z.ZodType) =>
  schema['~standard'].jsonSchema.output({ target: 'openapi-3.0' }) as never;

/**
 * Serves the document at `/openapi.json` and an interactive reference at
 * `/docs`, and the delivery document at `/openapi/delivery.json` (and
 * `.yaml`) with its reference at `/docs/delivery`.
 */
export function setUpOpenApi(app: INestApplication): void {
  // Before `/docs`, whose static files would otherwise answer `/docs/delivery`.
  SwaggerModule.setup('docs/delivery', app, () => createDeliveryDocument(app), {
    jsonDocumentUrl: 'openapi/delivery.json',
    yamlDocumentUrl: 'openapi/delivery.yaml',
  });
  SwaggerModule.setup('docs', app, () => createOpenApiDocument(app), {
    jsonDocumentUrl: 'openapi.json',
    yamlDocumentUrl: 'openapi.yaml',
  });
}
